def locales_dir() -> Path:
    """``app/locales`` in a source run, the Windows embed build and frozen PyInstaller builds."""
    from core.paths import resource_base
    return Path(resource_base()) / "app" / "locales"


@dataclass(frozen=True)
class _Catalog:
    code: str
    messages: Mapping[str, Any]
    nforms: int
    rule: Callable[[int], int]
    direction: str
    pseudo: bool = False
    english: bool = False
    #: Translated lines get RLE ... PDF (a right-to-left catalog on an RTL_PLATFORMS system).
    rtl_marks: bool = False


def _english_catalog() -> _Catalog:
    return _Catalog(SOURCE_LANGUAGE, {}, 2, _one_other, "ltr", english=True)


_STATE: _Catalog = _english_catalog()
_LOCK = threading.Lock()
_WARN_LOCK = threading.Lock()
_WARNED: set[tuple[str, ...]] = set()
_DOC_CACHE: dict[str, tuple[tuple[int, int], dict[str, Any] | None]] = {}


def _warn_once(key: tuple[str, ...], message: str, *args: object) -> None:
    with _WARN_LOCK:
        if key in _WARNED:
            return
        _WARNED.add(key)
    logger.warning(message, *args)


def _read_document(code: str) -> dict[str, Any] | None:
    """The parsed catalog file of ``code``, or None (with one warning) when it is unusable."""
    path = locales_dir() / f"{code}.json"
    try:
        st = path.stat()
    except FileNotFoundError:
        _warn_once(("missing", code), "No interface catalog for %s at %s; using English", code, path)
        return None
    except OSError as e:
        _warn_once(("unreadable", code), "Cannot read the interface catalog %s (%s); using English",
                   path, e)
        return None
    stamp = (st.st_mtime_ns, st.st_size)
    cached = _DOC_CACHE.get(code)
    if cached is not None and cached[0] == stamp:
        return cached[1]
    doc: dict[str, Any] | None = None
    try:
        data = json.loads(path.read_bytes().decode("utf-8"))
        problem = _document_problem(code, data)
        if problem:
            _warn_once(("malformed", code), "The interface catalog %s is not usable (%s); using English",
                       path, problem)
        else:
            doc = data
    except (OSError, UnicodeDecodeError, ValueError, RecursionError) as e:
        _warn_once(("malformed", code), "The interface catalog %s is not usable (%s); using English",
                   path, e)
    _DOC_CACHE[code] = (stamp, doc)
    return doc


def _document_problem(code: str, data: object) -> str:
    if not isinstance(data, dict):
        return "not a JSON object"
    meta = data.get("_meta")
    if not isinstance(meta, dict):
        return "no _meta object"
    if meta.get("code") != code:
        return f"_meta.code is {meta.get('code')!r}, the file name says {code!r}"
    if meta.get("status") not in STATUSES:
        return f"_meta.status {meta.get('status')!r} is not one of {', '.join(STATUSES)}"
    if not isinstance(data.get("messages"), dict):
        return "no messages object"
    return ""


def catalog_status(code: str) -> str | None:
    """The ``_meta.status`` of ``code``'s catalog, or None when it has no usable catalog."""
    if code == SOURCE_LANGUAGE:
        return "source"
    if code not in LANGUAGES_BY_CODE:
        return None
    doc = _read_document(code)
    return None if doc is None else str(doc["_meta"]["status"])


class _CatalogStatuses(Mapping[str, str]):
    """code -> catalog status for every catalog on disk, read only for the codes asked about."""

    def __getitem__(self, code: str) -> str:
        if code not in LANGUAGES_BY_CODE:
            raise KeyError(code)
        if code != SOURCE_LANGUAGE and not (locales_dir() / f"{code}.json").is_file():
            raise KeyError(code)
        status = catalog_status(code)
        if status is None:
            raise KeyError(code)
        return status

    def __iter__(self) -> Iterator[str]:
        for lang in SUPPORTED_LANGUAGES:
            if lang.code in self:
                yield lang.code

    def __len__(self) -> int:
        return sum(1 for _code in self)


def catalog_statuses() -> Mapping[str, str]:
    """The ``available`` argument of :func:`resolve_language` for the catalogs that ship."""
    return _CatalogStatuses()


def available_languages() -> list[LanguageInfo]:
    """The languages the picker offers, in ``SUPPORTED_LANGUAGES`` order.

    English and every usable catalog: status "reviewed", and status "machine" (unreviewed
    machine translation; the picker lists it like the others). A right-to-left catalog is offered only where
    :func:`rtl_layout_ready`. The pseudo-locale is never listed.
    """
    out: list[LanguageInfo] = []
    rtl_ok = rtl_layout_ready()
    for lang in SUPPORTED_LANGUAGES:
        if lang.direction == "rtl" and not rtl_ok:
            continue
        status = catalog_status(lang.code) if (
            lang.code == SOURCE_LANGUAGE or (locales_dir() / f"{lang.code}.json").is_file()) else None
        if status in STATUSES:
            out.append(LanguageInfo(lang.code, lang.endonym, lang.direction, str(status)))
    return out


# --- choosing the language -----------------------------------------------------------------

_ALIASES = {"iw": "he", "in": "id", "no": "nb", "tl": "fil", "zh": "zh-Hans"}
_ZH_HANT_REGIONS = {"tw", "hk", "mo"}


def _clean_tag(tag: str) -> str:
    """'pt_BR.UTF-8@euro' -> 'pt-BR'."""
    return tag.split(".")[0].split("@")[0].strip().replace("_", "-")


def _canonical(tag: str) -> str | None:
    """The SUPPORTED_LANGUAGES code ``tag`` names exactly (any case, '_' or '-'), or None."""
    cleaned = _clean_tag(tag)
    low = cleaned.lower()
    if low in _CODE_BY_LOWER:
        return _CODE_BY_LOWER[low]
    parts = low.split("-")
    if parts[0] == "zh" and len(parts) > 1:
        if "hant" in parts[1:] or any(p in _ZH_HANT_REGIONS for p in parts[1:]):
            return "zh-Hant"
        return "zh-Hans"
    if low in _ALIASES:
        return _ALIASES[low]
    return None


def _candidates(os_language: str) -> list[str]:
    """Codes to try for an OS language, most specific first: 'pt-BR' -> 'pt-BR', 'pt'."""
    cleaned = _clean_tag(os_language)
    if not cleaned:
        return []
    out: list[str] = []
    exact = _canonical(cleaned)
    if exact:
        out.append(exact)
    base = cleaned.split("-")[0]
    base_code = _canonical(base) or base.lower()
    if base_code not in out:
        out.append(base_code)
    return out


def _is_auto(value: object) -> bool:
    return value is None or (isinstance(value, str) and value.strip().lower() in ("", "auto"))


def resolve_language(value: object, *, os_language: str | None, available: Mapping[str, str]) -> str:
    """The language to use for config value ``value`` ("auto" or a language code).

    "auto" takes the OS language when a catalog for it ships, reviewed or machine-translated (the
    picker labels the latter, so a person can switch back), trying the region first and then the
    base language ('pt-BR' -> 'pt-BR', 'pt'; 'zh-TW'/'zh-HK' -> 'zh-Hant'; 'zh-CN'/'zh-SG' ->
    'zh-Hans'); otherwise English. "auto" never takes a right-to-left catalog where
    :func:`rtl_layout_ready` is False. An explicit code uses its catalog whatever its status, or
    English with one warning when there is none. "qps-ploc" selects the pseudo-locale.
    ``available`` maps code -> catalog status (:func:`catalog_statuses`).
    """
    if _is_auto(value):
        for code in _candidates(os_language or ""):
            if code == SOURCE_LANGUAGE:
                return SOURCE_LANGUAGE
            lang = LANGUAGES_BY_CODE.get(code)
            if lang is None or (lang.direction == "rtl" and not rtl_layout_ready()):
                continue
            if available.get(code) in _AUTO_STATUSES:
                return code
        return SOURCE_LANGUAGE
    if not isinstance(value, str):
        _warn_once(("ui_language", repr(value)), "ui_language %r is not a language code; using English",
                   value)
        return SOURCE_LANGUAGE
    if value.strip().lower() == PSEUDO_LOCALE:
        return PSEUDO_LOCALE
    for code in _candidates(value):  # 'de-AT' -> 'de-AT', then 'de'
        if code == SOURCE_LANGUAGE:
            return SOURCE_LANGUAGE
        if code in LANGUAGES_BY_CODE and code in available:
            return code
    _warn_once(("ui_language", value), "ui_language %r has no interface catalog; using English", value)
    return SOURCE_LANGUAGE


def _windows_ui_language() -> int:
    import ctypes
    windll = getattr(ctypes, "windll")
    return int(windll.kernel32.GetUserDefaultUILanguage())


def _usable_locale_name(value: str | None) -> str | None:
    if not value:
        return None
    cleaned = _clean_tag(value)
    if not cleaned or cleaned.upper() in ("C", "POSIX"):
        return None
    return cleaned


_MAC_DEFAULTS = "/usr/bin/defaults"
_MAC_DEFAULTS_TIMEOUT_S = 3.0
# One entry of an old-style plist array: a quoted string ("zh-Hans-CN") or a bare word (en).
_APPLE_LANGUAGE_ENTRY = re.compile(r'"((?:[^"\\]|\\.)*)"|([^\s,()"]+)')


def parse_apple_languages(output: str) -> str | None:
    """The first language of ``defaults read -g AppleLanguages`` output, or None.

    The output is an old-style plist array, one entry per line: ``(\\n    "de-DE",\\n    en\\n)``
    (entries with a hyphen are quoted, plain ones are not).
    """
    text = output.strip()
    if len(text) < 2 or text[0] != "(" or text[-1] != ")":
        return None
    for m in _APPLE_LANGUAGE_ENTRY.finditer(text[1:-1]):
        entry = (m.group(1) if m.group(1) is not None else m.group(2)).strip()
        if entry:
            return entry
    return None


def _mac_preferred_language() -> str | None:
    """The first of the macOS user's preferred languages (System Settings > Language & Region).

    A frozen app started from Finder has no LANG, and ``locale.getlocale()`` follows the region
    format rather than the language list, so the list is read where macOS keeps it. None (with
    one warning in the log) when it cannot be read.
    """
    import subprocess
    try:
        done = subprocess.run(
            [_MAC_DEFAULTS, "read", "-g", "AppleLanguages"], stdin=subprocess.DEVNULL,
            capture_output=True, text=True,
            encoding="utf-8", errors="replace", timeout=_MAC_DEFAULTS_TIMEOUT_S, check=False)
    except (OSError, subprocess.SubprocessError) as e:
        logger.warning("Could not read the macOS preferred languages (%s: %s); using the locale",
                       type(e).__name__, e)
        return None
    if done.returncode != 0:
        logger.warning("Reading the macOS preferred languages failed (exit %s: %s); using the locale",
                       done.returncode, (done.stderr or "").strip()[:200])
        return None
    found = parse_apple_languages(done.stdout or "")
    if found is None:
        logger.warning("Unexpected macOS preferred languages %r; using the locale",
                       (done.stdout or "")[:200])
    return found


def detect_os_language(
    *,
    platform: str | None = None,
    environ: Mapping[str, str] | None = None,
    windows_ui_language: Callable[[], int] | None = None,
    getlocale: Callable[[], tuple[str | None, str | None]] | None = None,
    mac_preferred_language: Callable[[], str | None] | None = None,
) -> str | None:
    """The operating system's interface language as a tag like 'pt-BR', or None. Never raises.

    Windows: the user's display language (GetUserDefaultUILanguage) named through
    ``locale.windows_locale``. macOS: the first preferred language (AppleLanguages). Then, and
    on Linux: LC_ALL, LC_MESSAGES, LANG, then ``locale.getlocale()``. The keyword arguments
    replace the real sources in tests.
    """
    try:
        current = platform or sys.platform
        if current == "win32":
            langid = (windows_ui_language or _windows_ui_language)()
            name = locale.windows_locale.get(langid) if langid else None
            if name:
                return name.replace("_", "-")
        if current == "darwin":
            found = _usable_locale_name((mac_preferred_language or _mac_preferred_language)())
            if found:
                return found
        env = os.environ if environ is None else environ
        for var in ("LC_ALL", "LC_MESSAGES", "LANG"):
            found = _usable_locale_name(env.get(var))
            if found:
                return found
        return _usable_locale_name((getlocale or locale.getlocale)()[0])
    except Exception:  # noqa: BLE001 - the language is a nicety; English always works
        logger.warning("Could not read the operating system language", exc_info=True)
        return None


def set_language(code: str) -> str:
    """Make ``code`` the interface language; returns the code actually used.

    "en" and unknown codes use the English source text (an unknown code logs one warning);
    "qps-ploc" is the pseudo-locale; any other code loads ``app/locales/<code>.json`` and falls
    back to English (one warning) when that file is missing or broken. Call it at start-up,
    before any widget text is created: texts already on screen do not change.
    """
    global _STATE
    if isinstance(code, str) and code.strip().lower() == PSEUDO_LOCALE:
        new = _Catalog(PSEUDO_LOCALE, {}, 2, _one_other, "ltr", pseudo=True)
    else:
        canonical = _canonical(code) if isinstance(code, str) else None
        if canonical is None:
            _warn_once(("set_language", repr(code)), "Unknown interface language %r; using English", code)
        new = _english_catalog()
        if canonical is not None and canonical != SOURCE_LANGUAGE:
            doc = _read_document(canonical)
            if doc is not None:
                lang = LANGUAGES_BY_CODE[canonical]
                meta_rule = doc["_meta"].get("plural")
                if meta_rule != lang.plural:
                    _warn_once(("plural", canonical),
                               "Catalog %s says plural rule %r; using the built-in %r",
                               canonical, meta_rule, lang.plural)
                nforms, rule = PLURAL_RULES[lang.plural]
                new = _Catalog(canonical, dict(doc["messages"]), nforms, rule, lang.direction,
                               rtl_marks=lang.direction == "rtl" and sys.platform in RTL_PLATFORMS)
    with _LOCK:
        _STATE = new
    return new.code


def current_language() -> str:
    return _STATE.code


def current_direction() -> str:
    """'rtl' for Arabic, Persian and Hebrew, else 'ltr'."""
    return _STATE.direction


def rtl_marks() -> bool:
    """True when translated texts carry the RLE ... PDF marks of :func:`embed_rtl`."""
    return _STATE.rtl_marks


def _has_rtl_letter(text: str) -> bool:
    return any(unicodedata.bidirectional(ch) in ("R", "AL") for ch in text)


def _wrapped(core: str) -> bool:
    """True when one RLE ... PDF pair encloses all of ``core`` (not "RLE a PDF b RLE c PDF")."""
    if not core.startswith(RLE) or not core.endswith(PDF):
        return False
    depth = 0
    for i, ch in enumerate(core):
        if ch in _OPENERS:
            depth += 1
        elif ch == PDF:
            depth -= 1
            if depth == 0:
                return i == len(core) - 1
    return False


def _embed_line(line: str) -> str:
    core = line.strip()
    if not core or _wrapped(core) or not _has_rtl_letter(core):
        return line
    lead = len(line) - len(line.lstrip())
    end = lead + len(core)
    return line[:lead] + RLE + core + PDF + line[end:]


def embed_rtl(text: str) -> str:
    """``text`` with each line that holds a right-to-left letter wrapped in RLE ... PDF.

    Tk draws every string with a left-to-right base direction, so a Persian sentence with a
    Latin word or a number in it, or ending in ":" or ")", comes out in the wrong order. The
    embedding makes each line right to left. It does not reach past a line break, so each line
    gets its own pair. Whitespace at the edges of a line stays outside the pair (``strip()``
    works as before); empty lines, lines without a right-to-left letter (a Latin file name, a
    number) and lines already wrapped are left as they are. Never the isolates U+2066..U+2069:
    Tk on Windows draws them as boxes.
    """
    if "\n" not in text:
        return _embed_line(text)
    return "\n".join(_embed_line(line) for line in text.split("\n"))


def plain(text: str) -> str:
    """``text`` without the embedding marks (U+202A..U+202E) :func:`embed_rtl` adds.

    For a translated text that leaves the screen: the log file, the clipboard, a file.
    """
    return _EMBEDDING_MARKS.sub("", text)


# The OS language once detected in this process: (it,) or empty. It does not change while the app
# runs, and on macOS reading it starts a process.
_OS_LANGUAGE: list[str | None] = []


def _os_language(environ: Mapping[str, str] | None = None) -> str | None:
    if environ is not None:
        return detect_os_language(environ=environ)
    if not _OS_LANGUAGE:
        _OS_LANGUAGE.append(detect_os_language())
    return _OS_LANGUAGE[0]


def setting_language(value: object) -> str:
    """The language ``ui_language`` = ``value`` gives at the next start, as :func:`init_language`
    would choose it (a ``WTS_UI_LANGUAGE`` override aside). Compare it with
    :func:`current_language` to tell whether a changed setting needs a restart."""
    os_language = _os_language() if _is_auto(value) else None
    return resolve_language(value, os_language=os_language, available=catalog_statuses())


def init_language(load_config: Callable[[], Mapping[str, Any]] | None = None,
                  environ: Mapping[str, str] | None = None) -> str:
    """Choose and set the interface language at start-up; returns the code used. Never raises.

    ``WTS_UI_LANGUAGE`` wins over the ``ui_language`` config key. ``load_config`` returns the
    config (``app.run`` passes ``core.config.load_config(fetch_online=False)``: no network
    before the window opens).
    """
    try:
        env = os.environ if environ is None else environ
        value: object = env.get(ENV_LANGUAGE, "").strip()
        if not value and load_config is not None:
            try:
                value = load_config().get("ui_language", "auto")
            except Exception:  # noqa: BLE001 - a config problem must not stop the app opening
                logger.warning("Could not read ui_language from the config; using auto", exc_info=True)
                value = "auto"
        os_language = _os_language(environ) if _is_auto(value) else None
        chosen = resolve_language(value, os_language=os_language, available=catalog_statuses())
        used = set_language(chosen)
        logger.info("Interface language: %s (setting %r, system %r)", used, value, os_language)
        return used
    except Exception:  # noqa: BLE001 - English always works
        logger.warning("Could not choose the interface language; using English", exc_info=True)
        return set_language(SOURCE_LANGUAGE)


# --- lookups -------------------------------------------------------------------------------

_FORMAT_ERRORS = (KeyError, IndexError, ValueError, AttributeError, TypeError)


def _finish(english: str, translated: str | None, kwargs: Mapping[str, Any], state: _Catalog,
            key: str) -> str:
    """The text shown: ``translated`` (formatted) when there is one, else the English text.

    Only a catalog translation gets the right-to-left marks (:func:`embed_rtl`); the English
    fallback and the pseudo-locale never do.
    """
    if not kwargs:
        if not translated:
            return english
        return embed_rtl(translated) if state.rtl_marks else translated
    fallback = english.format(**kwargs)  # a wrong call raises here, in every language
    if not translated:
        return fallback
    try:
        done = translated.format(**kwargs)
    except _FORMAT_ERRORS as e:
        _warn_once(("format", state.code, key),
                   "Translation of %r in %s does not fit its placeholders (%s: %s); using English",
                   key, state.code, type(e).__name__, e)
        return fallback
    return embed_rtl(done) if state.rtl_marks else done


def _lookup(state: _Catalog, key: str) -> str | None:
    found = state.messages.get(key)
    if found is None or found == "":
        return None
    if isinstance(found, str):
        return found
    _warn_once(("type", state.code, key), "Catalog %s has a %s for %r, not a text; using English",
               state.code, type(found).__name__, key)
    return None


def _(msgid: str, **kwargs: Any) -> str:
    """``msgid`` in the interface language; with keyword arguments, formatted with them."""
    state = _STATE
    if state.english:
        return msgid.format(**kwargs) if kwargs else msgid
    translated = pseudo_translate(msgid) if state.pseudo else _lookup(state, msgid)
    return _finish(msgid, translated, kwargs, state, msgid)


def text_in(code: str, msgid: str, **kwargs: Any) -> str:
    """``msgid`` in language ``code`` (English when it has no catalog or no entry), for a prompt
    that must speak a language the app is not running in. No right-to-left marks are added."""
    translated: str | None = None
    if code != SOURCE_LANGUAGE and code in LANGUAGES_BY_CODE:
        doc = _read_document(code)
        found = doc["messages"].get(msgid) if doc else None
        translated = found if isinstance(found, str) and found else None
    if translated:
        try:
            return translated.format(**kwargs) if kwargs else translated
        except _FORMAT_ERRORS:
            pass
    return msgid.format(**kwargs) if kwargs else msgid


def translate(msgid: str, **kwargs: Any) -> str:
    """:func:`_` for a text that is not a literal here: a constant marked with :func:`N_`."""
    return _(msgid, **kwargs)


def pgettext(context: str, msgid: str, **kwargs: Any) -> str:
    """``msgid`` in the sense ``context`` gives it ('menu' "Open" vs 'state' "Open")."""
    state = _STATE
    if state.english:
        return msgid.format(**kwargs) if kwargs else msgid
    key = context + CONTEXT_SEPARATOR + msgid
    translated = pseudo_translate(msgid) if state.pseudo else _lookup(state, key)
    return _finish(msgid, translated, kwargs, state, key)


def ngettext(singular: str, plural: str, n: int, **kwargs: Any) -> str:
    """The form for count ``n``: "{n} file" / "{n} files". ``{n}`` is always available."""
    values = {"n": n, **kwargs}
    english = singular if plural_index("one_other", n) == 0 else plural
    state = _STATE
    if state.english:
        return english.format(**values)
    translated: str | None = None
    if state.pseudo:
        translated = pseudo_translate(english)
    else:
        found = state.messages.get(singular)
        if isinstance(found, list) and len(found) == state.nforms and all(
                isinstance(f, str) for f in found):
            translated = found[state.rule(abs(int(n)))] or None
        elif found not in (None, "", []):
            _warn_once(("plural", state.code, singular),
                       "Catalog %s needs %d plural forms for %r; using English",
                       state.code, state.nforms, singular)
    return _finish(english, translated, values, state, singular)


def N_(msgid: str) -> str:  # noqa: N802 - the gettext name extractors and translators know
    """Mark a module-level constant for the extractor; translate it where it is shown."""
    return msgid


def lazy(msgid: str, **kwargs: Any) -> Callable[[], str]:
    """A callable that returns ``_(msgid, **kwargs)`` when called (tooltips take one)."""
    return functools.partial(_, msgid, **kwargs)



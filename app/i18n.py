"""Translation of the desktop app's own interface text (menus, buttons, labels, dialogs).

Standard library only. The guide for contributors and translators is ``docs/TRANSLATING.md``.

* ``_("Save")`` returns the text in the current interface language, or the English text when the
  catalog has no translation. ``_("Saved {name}", name=path)`` formats the result with
  ``str.format``; without keyword arguments the text is returned as it is.
* ``ngettext(singular, plural, n)`` picks the plural form by the language's rule; ``{n}`` is
  always available. ``pgettext(context, msgid)`` separates one English word with two meanings.
* ``N_`` marks a module-level constant for the extractor; translate it where it is shown with
  :func:`translate`. ``lazy`` returns a callable for APIs that take one (tooltips).

Catalogs are ``app/locales/<code>.json`` (``en.json`` is generated by ``tools/i18n_extract.py``).
The language is chosen once at start-up (:func:`init_language`, called by ``app.run`` before any
window is built); changing it needs a restart. Lookups never raise for a catalog problem: a missing
or broken catalog gives English and one warning in the log, a translation whose placeholders do not
fit gives the English text and one warning per message. A wrong call (the English text itself
cannot be formatted with the given arguments) does raise, so tests catch it.

Lookups are safe from any thread: the active catalog is one immutable object that only
:func:`set_language` replaces.
"""
